#!/usr/bin/env bash
# One-time setup of a rootless Nix on Sulu (safe to re-run).
#
#   scripts/sulu/setup.sh              install nix, nix.conf, sandbox shell, crontab
#   scripts/sulu/setup.sh attic-login  store the attic push token (read from stdin, not argv)
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=SCRIPTDIR/env.sh
. "$REPO_DIR/scripts/sulu/env.sh"

NIX_URL="https://hydra.nixos.org/job/nix/maintenance-2.35/buildStatic.nix-cli.x86_64-linux/latest/download-by-type/file/binary-dist"

check_scratch() {
  [ -d "$SCRATCH" ] || die "$SCRATCH does not exist"
  [ "$(stat -c %u "$SCRATCH")" = "$(id -u)" ] || die "$SCRATCH is not owned by $(id -un); ask before storing anything there"
  chmod 700 "$SCRATCH"
  mkdir -p "$SCRATCH"/{nix,build,logs,gcroots,tmp,.cache,.config/attic}
}

install_nix() {
  mkdir -p "$HOME/bin"
  log "downloading static nix"
  curl -fL --retry 3 -o "$HOME/bin/nix.new" "$NIX_URL"
  chmod +x "$HOME/bin/nix.new"
  "$HOME/bin/nix.new" --version
  sha256sum "$HOME/bin/nix.new"
  mv "$HOME/bin/nix.new" "$HOME/bin/nix"
}

write_nix_conf() {
  local sandbox_paths="${1:-}"
  cat > "$SCRATCH/nix.conf" <<EOF
# Generated by scripts/sulu/setup.sh
# Rootless "chroot" store: paths are /nix/store/... logically, stored under $SCRATCH/nix.
store = $SCRATCH/nix
build-dir = $SCRATCH/build
experimental-features = nix-command flakes
# Professor's limits: ~16 parallel jobs, one build at a time.
cores = 16
max-jobs = 1
sandbox = true
system-features = big-parallel
substituters = https://cache.nixos.org
trusted-public-keys = cache.nixos.org-1:6NCHdD59X431o0gWypbMrAURkbJ16ZPMQFGspcDShjY=
accept-flake-config = false
warn-dirty = false
${sandbox_paths}
EOF
}

install_sandbox_shell() {
  # The static nix's built-in /bin/sh for the sandbox doesn't exist here, so
  # fetch nixpkgs' busybox-sandbox-shell into the store and point at its
  # physical location. The gcroot keeps `nix store gc` from deleting it.
  log "fetching sandbox shell"
  local bb
  bb="$(nix build --option sandbox false --print-out-paths \
    --out-link "$SCRATCH/gcroots/sandbox-shell" \
    --inputs-from "path:$REPO_DIR" nixpkgs#busybox-sandbox-shell)"
  write_nix_conf "sandbox-paths = /bin/sh=$SCRATCH/nix$bb/bin/busybox"
}

test_sandbox() {
  log "testing a sandboxed build"
  nix build --no-link --print-out-paths --impure --expr "
    (builtins.getFlake \"path:$REPO_DIR\").inputs.nixpkgs.legacyPackages.x86_64-linux.runCommand
      \"sandbox-test-\${toString builtins.currentTime}\" {} ''
        /bin/sh -c 'echo ok' > \$out
      ''"
}

install_crontab() {
  local line="30 0 * * 6 $REPO_DIR/scripts/sulu/build.sh >> $SCRATCH/logs/cron.log 2>&1"
  ( crontab -l 2>/dev/null | grep -vF "scripts/sulu/build.sh" || true; echo "$line" ) | crontab -
  log "crontab:"
  crontab -l
  log "system timezone: $(date +%Z) (cron uses it; the schedule assumes $TZ_LOCAL)"
}

attic_login() {
  local token
  read -rsp "attic push token for $CACHE_NAME: " token
  echo
  [ -n "$token" ] || die "empty token"
  (
    umask 077
    cat > "$SCRATCH/.config/attic/config.toml" <<EOF
default-server = "poacher"

[servers.poacher]
endpoint = "https://cache.poacher.dev/"
token = "$token"
EOF
  )
  chmod 600 "$SCRATCH/.config/attic/config.toml"
  log "wrote $SCRATCH/.config/attic/config.toml (mode 600)"
}

case "${1:-setup}" in
  setup)
    check_scratch
    install_nix
    write_nix_conf
    install_sandbox_shell
    test_sandbox
    install_crontab
    log "done; now run: $0 attic-login"
    ;;
  attic-login)
    check_scratch
    attic_login
    ;;
  *)
    die "usage: $0 [setup|attic-login]"
    ;;
esac
